func TestCheckSourceAllowsCleanCodeAndDirectives(t *testing.T) {
	src := []byte(`//go:build linux && e2e

package sample

//go:noinline
func URL() string {
	return "https://example.com//path /* not a comment */"
}
`)

	violations, err := checkSource("sample.go", src)
	require.NoError(t, err)
	require.Empty(t, violations)
}

func TestCheckSourceSkipsGeneratedFiles(t *testing.T) {
	src := []byte(`// Code generated by tool. DO NOT EDIT.

package sample

// Generated doc comment.
func Foo() {}
`)

	violations, err := checkSource("generated.go", src)
	require.NoError(t, err)
	require.Empty(t, violations)
}

func TestCheckSourceRejectsDisallowedComments(t *testing.T) {
	tests := []struct {
		name string
		src  string
		line int
		col  int
	}{
		{
			name: "line comment",
			src:  "package sample\n\n// hello\nfunc Foo() {}\n",
			line: 3,
			col:  1,
		},
		{
			name: "inline comment",
			src:  "package sample\n\nfunc Foo() { _ = 1 // inline\n}\n",
			line: 3,
			col:  20,
		},
		{
			name: "block comment",
			src:  "package sample\n\n/* block */\nfunc Foo() {}\n",
			line: 3,
			col:  1,
		},
		{
			name: "nolint directive",
			src:  "package sample\n\n//nolint:gocritic // reason\nfunc Foo() {}\n",
			line: 3,
			col:  1,
		},
		{
			name: "spaced go directive",
			src:  "package sample\n\n// go:build linux\nfunc Foo() {}\n",
			line: 3,
			col:  1,
		},
		{
			name: "indented go directive",
			src:  "package sample\n\nfunc Foo() {\n\t//go:noinline\n}\n",
			line: 4,
			col:  2,
		},
		{
			name: "malformed go directive",
			src:  "package sample\n\n//go:NotADirective\nfunc Foo() {}\n",
			line: 3,
			col:  1,
		},
		{
			name: "unknown go directive",
			src:  "package sample\n\n//go:note fake comment\nfunc Foo() {}\n",
			line: 3,
			col:  1,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			violations, err := checkSource("sample.go", []byte(tc.src))
			require.NoError(t, err)
			require.Len(t, violations, 1)
			require.Equal(t, tc.line, violations[0].line)
			require.Equal(t, tc.col, violations[0].column)
		})
	}
}

func TestRunWalksTreeAndSkipsIgnoredDirs(t *testing.T) {
	dir := t.TempDir()

	writeTestFile(t, filepath.Join(dir, "clean.go"), "//go:build unix\n\npackage sample\n")
	writeTestFile(t, filepath.Join(dir, "gen", "proto.pb.go"), "package gen\n\n// allowed in gen dir\n")
	writeTestFile(t, filepath.Join(dir, "vendor", "dep.go"), "package dep\n\n// allowed in vendor dir\n")
	writeTestFile(t, filepath.Join(dir, ".worktrees", "wt.go"), "package wt\n\n// allowed in worktrees dir\n")
	writeTestFile(t, filepath.Join(dir, "pkg", "bad.go"), "package pkg\n\n// disallowed\n")

	var stdout, stderr bytes.Buffer
	code := run([]string{dir}, &stdout, &stderr)
	require.Equal(t, 1, code)
	require.Empty(t, stderr.String())
	require.Equal(t, 1, strings.Count(stdout.String(), "\n"))
	require.Contains(t, stdout.String(), filepath.Join(dir, "pkg", "bad.go")+":3:1:")
}

func TestRunReturnsZeroWhenClean(t *testing.T) {
	dir := t.TempDir()
	writeTestFile(t, filepath.Join(dir, "clean.go"), "package sample\n\nfunc Answer() int { return 42 }\n")

	var stdout, stderr bytes.Buffer
	code := run([]string{dir}, &stdout, &stderr)
	require.Equal(t, 0, code)
	require.Empty(t, stdout.String())
	require.Empty(t, stderr.String())
}

func writeTestFile(t *testing.T, path, content string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
}
